/**
 * Reads assets/coloring/*.svg and generates src/game/pictures.data.ts.
 *
 * Conventions per SVG file:
 *   - <svg viewBox="..." data-title="Flower" data-emoji="🌸">
 *   - filename (minus .svg) is the picture id, also the route param
 *   - every colorable element MUST have an `id` attribute
 *     (path | circle | ellipse | rect | polygon)
 *   - document order = paint order (first = bottom layer)
 *   - anything inside <g id="decorations"> is stroke-only detail (paths),
 *     never colorable, never counts toward "finished"
 *
 * Run: npm run gen:pictures
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseSync } from "svgson";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC_DIR = join(root, "assets", "coloring");
const OUT = join(root, "src", "game", "pictures.data.ts");

const SHAPE_KINDS = new Set(["path", "circle", "ellipse", "rect", "polygon"]);
const num = (v) => (v == null ? undefined : Number(v));

function toRegion(node) {
  const a = node.attributes;
  const base = { id: a.id, ...(a.transform ? { transform: a.transform } : {}) };
  switch (node.name) {
    case "path":
      return { ...base, kind: "path", d: a.d };
    case "circle":
      return { ...base, kind: "circle", cx: num(a.cx), cy: num(a.cy), r: num(a.r) };
    case "ellipse":
      return {
        ...base,
        kind: "ellipse",
        cx: num(a.cx),
        cy: num(a.cy),
        rx: num(a.rx),
        ry: num(a.ry),
      };
    case "rect":
      return {
        ...base,
        kind: "rect",
        x: num(a.x),
        y: num(a.y),
        width: num(a.width),
        height: num(a.height),
        ...(a.rx ? { rx: num(a.rx) } : {}),
      };
    case "polygon":
      return { ...base, kind: "polygon", points: a.points };
  }
}

function build(id, svgText) {
  const svg = parseSync(svgText);
  const viewBox = svg.attributes.viewBox;
  if (!viewBox) throw new Error(`${id}.svg: missing viewBox`);

  const regions = [];
  const decorations = [];

  for (const node of svg.children) {
    if (node.name === "g" && node.attributes.id === "decorations") {
      for (const d of node.children) {
        if (d.name === "path" && d.attributes.d) decorations.push({ d: d.attributes.d });
      }
      continue;
    }
    if (!SHAPE_KINDS.has(node.name)) continue;
    if (!node.attributes.id) {
      throw new Error(`${id}.svg: <${node.name}> has no id (every colorable shape needs one)`);
    }
    regions.push(toRegion(node));
  }

  if (regions.length === 0) throw new Error(`${id}.svg: no colorable regions found`);

  return {
    id,
    title: svg.attributes["data-title"] ?? id[0].toUpperCase() + id.slice(1),
    emoji: svg.attributes["data-emoji"] ?? "🎨",
    viewBox,
    regions,
    decorations,
  };
}

const files = readdirSync(SRC_DIR)
  .filter((f) => f.endsWith(".svg"))
  .sort();

const pictures = files.map((f) => build(f.replace(/\.svg$/, ""), readFileSync(join(SRC_DIR, f), "utf8")));

const banner = `// GENERATED by scripts/generate-pictures.mjs — do not edit.
// Source: assets/coloring/*.svg  ·  regenerate: npm run gen:pictures
`;

writeFileSync(
  OUT,
  `${banner}
import type { Picture } from "./pictures.types";

export const PICTURES: Picture[] = ${JSON.stringify(pictures, null, 2)};
`
);

console.log(`wrote ${OUT}`);
for (const p of pictures) {
  console.log(`  ${p.emoji} ${p.id.padEnd(12)} ${p.regions.length} regions, ${p.decorations.length} decorations`);
}
